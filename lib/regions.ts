// ──────────────────────────────────────────────────────────────
// 시/도 정규화 & 인접 광역 매핑 (지역 기반 추천용)
//
// 사용자 프로필 region 은 정식 라벨('서울특별시')이지만, 전문가 region 은 자유
// 입력('서울 강남', '경기 수원')이라 표기가 다르다. 양쪽을 아래 canonical 키(축약
// 시/도)로 정규화해 같은 광역인지 비교한다.
// ──────────────────────────────────────────────────────────────

export type RegionKey =
  | '서울' | '부산' | '대구' | '인천' | '광주' | '대전' | '울산' | '세종'
  | '경기' | '강원' | '충북' | '충남' | '전북' | '전남' | '경북' | '경남' | '제주';

// canonical 키 → 표기 변형(접두어). raw 값의 첫 토큰이 이 접두어로 시작하면 매칭.
const REGION_ALIASES: Record<RegionKey, string[]> = {
  서울: ['서울'],
  부산: ['부산'],
  대구: ['대구'],
  인천: ['인천'],
  광주: ['광주'],
  대전: ['대전'],
  울산: ['울산'],
  세종: ['세종'],
  경기: ['경기'],
  강원: ['강원'],
  충북: ['충북', '충청북'],
  충남: ['충남', '충청남'],
  전북: ['전북', '전라북'],
  전남: ['전남', '전라남'],
  경북: ['경북', '경상북'],
  경남: ['경남', '경상남'],
  제주: ['제주'],
};

const REGION_KEYS = Object.keys(REGION_ALIASES) as RegionKey[];

// 임의 지역 문자열('서울특별시' / '서울 강남' / '경기 수원')을 축약 시/도 키로 정규화.
// 매칭 실패 시 null.
export function canonicalRegionKey(raw?: string | null): RegionKey | null {
  if (!raw) return null;
  const head = raw.trim().split(/\s+/)[0];
  if (!head) return null;
  for (const key of REGION_KEYS) {
    if (REGION_ALIASES[key].some((alias) => head.startsWith(alias))) return key;
  }
  return null;
}

// 인접(인근) 광역 매핑. 가까운 순 우선. 지리적 경계 기준 근사치이며, 실제 서비스
// 반경 정책이 정해지면 조정한다. 제주는 육지 인접이 없어 빈 배열(→ 전지역 폴백).
